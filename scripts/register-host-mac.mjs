// macOS 上注册 BrowserPilot native messaging host（com.browserpilot.browseragent）。
// Windows 走 native-host/register.ps1（注册表 + SEA exe）；mac 的注册方式是把 manifest JSON
// 放进浏览器的 NativeMessagingHosts 目录，path 指向一个用本机 node 直跑 host.js 的 wrapper。
// 用法：node scripts/register-host-mac.mjs            # 注册（Chrome，及已安装的 Edge/Chromium/Brave）
//       node scripts/register-host-mac.mjs --unregister
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const nativeHostDir = path.join(root, "native-host");
const HOST_NAME = "com.browserpilot.browseragent";
const unregister = process.argv.includes("--unregister");

// 扩展 ID 由 manifest.json 的 key 固定（任何机器加载都得到同一 ID）：
// sha256(DER SPKI) 前 32 个 hex 位，0-9a-f 映射为 a-p。
function extensionIdFromKey() {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"));
  if (!manifest.key) throw new Error("manifest.json 缺少 key，无法推导稳定扩展 ID");
  const hex = crypto.createHash("sha256").update(Buffer.from(manifest.key, "base64")).digest("hex");
  return [...hex.slice(0, 32)].map((c) => String.fromCharCode(parseInt(c, 16) + 97)).join("");
}

function registeredIdFromHostManifest() {
  try {
    const m = JSON.parse(fs.readFileSync(path.join(nativeHostDir, "host.manifest.json"), "utf8"));
    const origin = (m.allowed_origins ?? [])[0] ?? "";
    return String(origin).match(/^chrome-extension:\/\/([^/]+)\//)?.[1];
  } catch {
    return undefined;
  }
}

function nativeMessagingDirs() {
  const support = path.join(os.homedir(), "Library", "Application Support");
  const candidates = [
    ["Google Chrome", path.join(support, "Google", "Chrome", "NativeMessagingHosts")],
    ["Chromium", path.join(support, "Chromium", "NativeMessagingHosts")],
    ["Microsoft Edge", path.join(support, "Microsoft Edge", "NativeMessagingHosts")],
    ["Brave Browser", path.join(support, "BraveSoftware", "Brave-Browser", "NativeMessagingHosts")],
  ];
  const installed = candidates.filter(([, dir]) => fs.existsSync(path.dirname(dir)));
  return installed.length ? installed : [["Google Chrome", candidates[0][1]]];
}

const extensionId = extensionIdFromKey();
const fromHostManifest = registeredIdFromHostManifest();
if (fromHostManifest && fromHostManifest !== extensionId) {
  console.error(`扩展 ID 不一致：manifest.json key 推导出 ${extensionId}，host.manifest.json 记录 ${fromHostManifest}。请核对仓库状态。`);
  process.exit(1);
}

const wrapperPath = path.join(nativeHostDir, "dist", "host-mac.sh");
const manifestTargets = nativeMessagingDirs();

if (unregister) {
  for (const [browser, dir] of manifestTargets) {
    const file = path.join(dir, HOST_NAME + ".json");
    if (fs.existsSync(file)) {
      fs.unlinkSync(file);
      console.log("[unregister] removed " + browser + ": " + file);
    }
  }
  if (fs.existsSync(wrapperPath)) fs.unlinkSync(wrapperPath);
  console.log("done.");
  process.exit(0);
}

// wrapper：Chrome 会直接 exec 它，必须用 exec 保持同一进程与 stdin/stdout 协议通道。
const nodePath = process.execPath;
const hostEntry = path.join(nativeHostDir, "host.js");
fs.mkdirSync(path.dirname(wrapperPath), { recursive: true });
fs.writeFileSync(
  wrapperPath,
  "#!/bin/sh\n# Generated by scripts/register-host-mac.mjs — do not edit.\nexec " + JSON.stringify(nodePath) + " " + JSON.stringify(hostEntry) + ' "$@"\n',
  { mode: 0o755 },
);

const nativeManifest = {
  name: HOST_NAME,
  description: "BrowserPilot native messaging host",
  path: wrapperPath,
  type: "stdio",
  allowed_origins: ["chrome-extension://" + extensionId + "/"],
};

for (const [browser, dir] of manifestTargets) {
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, HOST_NAME + ".json");
  fs.writeFileSync(file, JSON.stringify(nativeManifest, null, 2) + "\n");
  console.log("[register] " + browser + ": " + file);
}

console.log(JSON.stringify({ extensionId, wrapper: wrapperPath, node: nodePath }, null, 2));
console.log("注册完成。下一步：在 " + browserLabel(manifestTargets) + " 加载 dist/（未打包扩展），扩展 SW 启动时会自动拉起 host。");
console.log("验证：npm run client -- ping '{}' --no-launch");

function browserLabel(targets) {
  return targets.map(([b]) => b).join(" / ");
}
