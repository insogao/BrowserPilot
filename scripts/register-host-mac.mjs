// macOS 上注册 BrowserPilot native messaging host（com.browserpilot.browseragent）。
// Windows 走 native-host/register.ps1（注册表 + SEA exe）；mac 的注册方式是把 manifest JSON
// 放进浏览器的 NativeMessagingHosts 目录，path 指向一个用本机 node 直跑 host.js 的 wrapper。
//
// 用法：
//   node scripts/register-host-mac.mjs [--user-data-dir <path>]... [--only-user-data-dir] [--dry-run] [--force]
//   node scripts/register-host-mac.mjs --unregister [--user-data-dir <path>]... [--only-user-data-dir]
//
// 目标发现（只注册父目录已存在的浏览器）：
//   Google Chrome / Chrome for Testing / Chromium / Microsoft Edge / Brave Browser。
//   Chrome for Testing 同时覆盖官方（ChromeForTesting）与品牌化产品目录（Chrome for Testing）两种形态。
// 自定义 user-data-dir：Chrome 的 --user-data-dir 会覆盖用户数据目录，用户级 host 从
//   <user-data-dir>/NativeMessagingHosts/ 查找；任何品牌的 Chrome / Chrome for Testing 通用，
//   --user-data-dir 显式声明目标，脚本不扫描运行中的进程。
//   --only-user-data-dir 只处理显式给出的 --user-data-dir，不发现也不写入默认浏览器目录；
//   使用它时必须至少给出一个 --user-data-dir。
//
// 安全：写入前先检查全部目标；若目标位置已存在不属于 BrowserPilot 的 manifest/wrapper，
// 默认拒绝且不写任何文件（--force 才覆盖）。注销永远只清理宿主名匹配的 manifest 与带生成标记的 wrapper。
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

export const HOST_NAME = "com.browserpilot.browseragent";
export const HOST_DESCRIPTION = "BrowserPilot native messaging host";
export const WRAPPER_MARKER = "Generated by scripts/register-host-mac.mjs";

const USAGE = [
  "macOS 注册 BrowserPilot native messaging host（" + HOST_NAME + "）",
  "",
  "用法：",
  "  node scripts/register-host-mac.mjs [--user-data-dir <path>]... [--only-user-data-dir] [--dry-run] [--force]",
  "  node scripts/register-host-mac.mjs --unregister [--user-data-dir <path>]... [--only-user-data-dir]",
  "",
  "自动发现并注册到父目录已存在的浏览器用户级 NativeMessagingHosts：",
  "  Google Chrome / Chrome for Testing / Chromium / Microsoft Edge / Brave Browser。",
  "自定义 user-data-dir（任意 Chrome / Chrome for Testing 通用）：",
  "  Chrome 用 <user-data-dir>/NativeMessagingHosts/ 查找用户级 host；",
  "  例如 node scripts/register-host-mac.mjs --user-data-dir \"/path/to/user data\"",
  "",
  "--only-user-data-dir  只处理显式给出的 --user-data-dir 目标，不发现也不写入",
  "                      默认浏览器目录；必须至少给出一个 --user-data-dir",
  "--dry-run             只检查并打印将执行的动作，不写文件",
  "--force               覆盖目标位置已存在的非 BrowserPilot manifest/wrapper",
].join("\n");

// 扩展 ID 由 manifest.json 的 key 固定（任何机器加载都得到同一 ID）：
// sha256(DER SPKI) 前 32 个 hex 位，0-9a-f 映射为 a-p。
export function extensionIdFromKey(key) {
  const hex = crypto.createHash("sha256").update(Buffer.from(key, "base64")).digest("hex");
  return [...hex.slice(0, 32)].map((c) => String.fromCharCode(parseInt(c, 16) + 97)).join("");
}

export function extensionIdFromRepo(root) {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"));
  if (!manifest.key) throw new Error("manifest.json 缺少 key，无法推导稳定扩展 ID");
  return extensionIdFromKey(manifest.key);
}

export function registeredIdFromHostManifest(root) {
  try {
    const m = JSON.parse(fs.readFileSync(path.join(root, "native-host", "host.manifest.json"), "utf8"));
    const origin = (m.allowed_origins ?? [])[0] ?? "";
    return String(origin).match(/^chrome-extension:\/\/([^/]+)\//)?.[1];
  } catch {
    return undefined;
  }
}

export function browserTargets(home = os.homedir()) {
  const support = path.join(home, "Library", "Application Support");
  const candidates = [
    ["Google Chrome", path.join(support, "Google", "Chrome", "NativeMessagingHosts")],
    ["Chrome for Testing", path.join(support, "Google", "ChromeForTesting", "NativeMessagingHosts")],
    ["Chrome for Testing (product dir)", path.join(support, "Google", "Chrome for Testing", "NativeMessagingHosts")],
    ["Chromium", path.join(support, "Chromium", "NativeMessagingHosts")],
    ["Microsoft Edge", path.join(support, "Microsoft Edge", "NativeMessagingHosts")],
    ["Brave Browser", path.join(support, "BraveSoftware", "Brave-Browser", "NativeMessagingHosts")],
  ];
  const installed = candidates.filter(([, dir]) => fs.existsSync(path.dirname(dir)));
  return installed.length ? installed : [["Google Chrome", candidates[0][1]]];
}

export function collectTargets({ home = os.homedir(), userDataDirs = [], onlyUserDataDirs = false } = {}) {
  if (onlyUserDataDirs && userDataDirs.length === 0) {
    throw new Error("--only-user-data-dir 需要至少一个 --user-data-dir 目标");
  }
  const targets = onlyUserDataDirs ? [] : browserTargets(home).map(([label, dir]) => ({ label, dir, kind: "browser" }));
  for (const raw of userDataDirs) {
    const userDataDir = path.resolve(raw);
    targets.push({
      label: "Chrome user-data-dir " + userDataDir,
      dir: path.join(userDataDir, "NativeMessagingHosts"),
      kind: "user-data-dir",
      userDataDir,
    });
  }
  const seen = new Set();
  return targets.filter((target) => {
    const key = path.resolve(target.dir);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

// wrapper：Chrome 会直接 exec 它，必须用 exec 保持同一进程与 stdin/stdout 协议通道。
export function buildWrapperContent({ nodePath, hostEntry }) {
  return "#!/bin/sh\n# " + WRAPPER_MARKER + " — do not edit.\nexec " + JSON.stringify(nodePath) + " " + JSON.stringify(hostEntry) + ' "$@"\n';
}

export function buildNativeManifest({ extensionId, wrapperPath }) {
  return {
    name: HOST_NAME,
    description: HOST_DESCRIPTION,
    path: wrapperPath,
    type: "stdio",
    allowed_origins: ["chrome-extension://" + extensionId + "/"],
  };
}

export function inspectManifest(file, { extensionId } = {}) {
  if (!fs.existsSync(file)) return { status: "missing", file };
  let text;
  try {
    text = fs.readFileSync(file, "utf8");
  } catch (error) {
    return { status: "foreign", file, reason: "无法读取: " + error.message };
  }
  let parsed;
  try {
    parsed = JSON.parse(text);
  } catch {
    return { status: "foreign", file, reason: "不是合法 JSON" };
  }
  if (!parsed || typeof parsed !== "object" || parsed.name !== HOST_NAME) {
    return { status: "foreign", file, reason: "name=" + JSON.stringify(parsed?.name) + " 不是 " + HOST_NAME };
  }
  const origins = Array.isArray(parsed.allowed_origins) ? parsed.allowed_origins : [];
  const origin = extensionId ? "chrome-extension://" + extensionId + "/" : undefined;
  if (origin && origins.length > 0 && !origins.includes(origin)) {
    return { status: "foreign", file, reason: "allowed_origins 属于其它扩展: " + origins.join(", ") };
  }
  return { status: "own", file, text };
}

export function inspectWrapper(wrapperPath) {
  if (!fs.existsSync(wrapperPath)) return { status: "missing", file: wrapperPath };
  const text = fs.readFileSync(wrapperPath, "utf8");
  if (text.includes(WRAPPER_MARKER)) return { status: "own", file: wrapperPath, text };
  return { status: "foreign", file: wrapperPath, reason: "缺少生成标记" };
}

export function registerHost({
  root,
  home = os.homedir(),
  userDataDirs = [],
  onlyUserDataDirs = false,
  nodePath = process.execPath,
  force = false,
  dryRun = false,
  log = console.log,
} = {}) {
  const extensionId = extensionIdFromRepo(root);
  const fromHostManifest = registeredIdFromHostManifest(root);
  if (fromHostManifest && fromHostManifest !== extensionId) {
    throw new Error("扩展 ID 不一致：manifest.json key 推导出 " + extensionId + "，host.manifest.json 记录 " + fromHostManifest + "。请核对仓库状态。");
  }

  const hostEntry = path.join(root, "native-host", "host.js");
  if (!fs.existsSync(hostEntry)) throw new Error("找不到 native host 入口: " + hostEntry);
  const wrapperPath = path.join(root, "native-host", "dist", "host-mac.sh");
  const manifestText = JSON.stringify(buildNativeManifest({ extensionId, wrapperPath }), null, 2) + "\n";
  const wrapperText = buildWrapperContent({ nodePath, hostEntry });

  const targets = collectTargets({ home, userDataDirs, onlyUserDataDirs });
  const wrapperState = inspectWrapper(wrapperPath);
  const manifestStates = new Map();
  const problems = [];
  if (wrapperState.status === "foreign" && !force) {
    problems.push(wrapperState.file + " 已存在但不是本脚本生成的 wrapper（" + wrapperState.reason + "）");
  }
  for (const target of targets) {
    if (target.kind === "user-data-dir") {
      let stat;
      try {
        stat = fs.statSync(target.userDataDir);
      } catch {
        stat = undefined;
      }
      if (!stat?.isDirectory()) problems.push("user-data-dir 不存在或不是目录: " + target.userDataDir);
    }
    const file = path.join(target.dir, HOST_NAME + ".json");
    const state = inspectManifest(file, { extensionId });
    manifestStates.set(file, state);
    if (state.status === "foreign" && !force) problems.push(file + " 已存在且不属于 BrowserPilot（" + state.reason + "）");
  }
  if (problems.length) {
    for (const problem of problems) log("[conflict] " + problem);
    throw new Error("存在冲突目标，未写入任何文件；确认后可用 --force 覆盖：\n" + problems.map((problem) => "- " + problem).join("\n"));
  }

  let wrapperStatus = wrapperState.status === "missing" ? "created" : wrapperState.text === wrapperText ? "unchanged" : "updated";
  if (!dryRun) {
    if (wrapperStatus !== "unchanged") {
      fs.mkdirSync(path.dirname(wrapperPath), { recursive: true });
      fs.writeFileSync(wrapperPath, wrapperText, { mode: 0o755 });
      fs.chmodSync(wrapperPath, 0o755);
    } else if ((fs.statSync(wrapperPath).mode & 0o111) === 0) {
      fs.chmodSync(wrapperPath, 0o755);
    }
  }
  log("[register] wrapper (" + (dryRun ? "dry-run " : "") + wrapperStatus + "): " + wrapperPath);

  const results = [];
  for (const target of targets) {
    const file = path.join(target.dir, HOST_NAME + ".json");
    const state = manifestStates.get(file);
    const status = state.status === "missing" ? "created" : state.text === manifestText ? "unchanged" : "updated";
    if (status !== "unchanged" && !dryRun) {
      fs.mkdirSync(target.dir, { recursive: true });
      fs.writeFileSync(file, manifestText);
    }
    log("[register] " + target.label + " (" + (dryRun ? "dry-run " : "") + status + "): " + file);
    results.push({ label: target.label, dir: target.dir, file, status });
  }

  return { extensionId, wrapperPath, wrapperStatus, dryRun, targets: results };
}

export function unregisterHost({
  root,
  home = os.homedir(),
  userDataDirs = [],
  onlyUserDataDirs = false,
  dryRun = false,
  log = console.log,
} = {}) {
  const targets = collectTargets({ home, userDataDirs, onlyUserDataDirs });
  const results = [];
  for (const target of targets) {
    const file = path.join(target.dir, HOST_NAME + ".json");
    const state = inspectManifest(file);
    if (state.status === "missing") {
      results.push({ label: target.label, dir: target.dir, file, status: "absent" });
      continue;
    }
    if (state.status === "foreign") {
      log("[unregister] skipped " + target.label + "（" + state.reason + "）: " + file);
      results.push({ label: target.label, dir: target.dir, file, status: "skipped" });
      continue;
    }
    if (!dryRun) fs.unlinkSync(file);
    log("[unregister] removed " + target.label + (dryRun ? " (dry-run)" : "") + ": " + file);
    results.push({ label: target.label, dir: target.dir, file, status: "removed" });
  }
  const wrapperPath = path.join(root, "native-host", "dist", "host-mac.sh");
  const wrapperState = inspectWrapper(wrapperPath);
  if (wrapperState.status === "own") {
    if (!dryRun) fs.unlinkSync(wrapperPath);
    log("[unregister] removed wrapper" + (dryRun ? " (dry-run)" : "") + ": " + wrapperPath);
  } else if (wrapperState.status === "foreign") {
    log("[unregister] skipped wrapper（" + wrapperState.reason + "）: " + wrapperPath);
  }
  return { dryRun, targets: results, wrapper: wrapperState.status };
}

export function parseArgs(argv) {
  const options = { unregister: false, force: false, dryRun: false, onlyUserDataDirs: false, help: false, userDataDirs: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--unregister") options.unregister = true;
    else if (arg === "--force") options.force = true;
    else if (arg === "--dry-run") options.dryRun = true;
    else if (arg === "--only-user-data-dir") options.onlyUserDataDirs = true;
    else if (arg === "--help" || arg === "-h") options.help = true;
    else if (arg === "--user-data-dir") {
      if (i + 1 >= argv.length) throw new Error("--user-data-dir 缺少路径参数");
      options.userDataDirs.push(argv[++i]);
    } else if (arg.startsWith("--user-data-dir=")) {
      const value = arg.slice("--user-data-dir=".length);
      if (!value) throw new Error("--user-data-dir 缺少路径参数");
      options.userDataDirs.push(value);
    } else {
      throw new Error("未知参数: " + arg + "（可用 --help 查看用法）");
    }
  }
  return options;
}

function browserLabel(targets) {
  return targets.map((target) => target.label).join(" / ");
}

function main(argv = process.argv.slice(2)) {
  const options = parseArgs(argv);
  if (options.help) {
    console.log(USAGE);
    return undefined;
  }
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  if (options.unregister) {
    const result = unregisterHost({ root, userDataDirs: options.userDataDirs, onlyUserDataDirs: options.onlyUserDataDirs, dryRun: options.dryRun });
    console.log("done.");
    return result;
  }
  const result = registerHost({ root, userDataDirs: options.userDataDirs, onlyUserDataDirs: options.onlyUserDataDirs, force: options.force, dryRun: options.dryRun });
  console.log(JSON.stringify({ extensionId: result.extensionId, wrapper: result.wrapperPath, node: process.execPath, dryRun: result.dryRun, targets: result.targets.map((target) => target.dir) }, null, 2));
  if (result.dryRun) {
    console.log("dry-run：未写入任何文件。");
  } else {
    console.log("注册完成。下一步：在 " + browserLabel(result.targets) + " 加载 dist/（未打包扩展），扩展 SW 启动时会自动拉起 host。");
    console.log("验证：npm run client -- ping '{}' --no-launch");
  }
  return result;
}

// macOS 的 $TMPDIR 常见 /var → /private/var 符号链接：按 realpath 比较入口，避免复制执行的脚本被当成 import。
function isMainModule() {
  if (!process.argv[1]) return false;
  try {
    return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMainModule()) {
  try {
    main();
  } catch (error) {
    console.error("[error] " + error.message);
    process.exit(1);
  }
}
